/* 注：原 S0553_PROGRAM_MAX / S0553_WISE_MAX 已从本头文件移除。
   理由：【程序数量 / 手法数量属于业务取值范围，归主控持有】（范围钳制也在主控侧），
   显示组件本身不需要知道——它只是显示主控给的值。
   组件侧用到"数量"的地方改为由表自身得出：
     - 程序名 / 手法名表尺寸 → sizeof(表)（见 S0553_UI_Config.c）
     - 图标数量             → S0553_ImageTable.h 的 *_ICON_COUNT
   主控侧自行定义其持有的范围，并在下发前完成钳制。 */

/**
 * @brief 开机流程页面配置（由 UI 配置层决定，引擎不再写死具体页面号）
 * @details S0553_SPLASH_PAGE：开机时先显示的页面，其 OnEnter 钩子负责预约"停留后跳转"；
 *          S0553_BOOT_PAGE  ：开机完成后进入的页面，也用作引擎的非法入参兜底。
 *          改开机页/首页只需改这里，无需动 S0553_Display.c。
 */
#define S0553_SPLASH_PAGE  S0553_DISP_TYPE_LOGO   /**< 开机先显示的页面 */
#define S0553_BOOT_PAGE    S0553_DISP_TYPE_MAIN   /**< 开机完成后进入的页面 */

/**
 * @brief 文本资源ID（声明式 UI 配置用）
 * @details TEXT 图层将 Text 置 NULL、TextId 置此枚举值，渲染时由 S0553UI_ResolveText
 *         按 (TextId, 主板自动程序序号, 语言) 解析出实际 UTF-8 字符串。
 */
typedef enum
{
    TEXTRES_MAIN_PROGRAM_NAME = 1,  /**< 主页面：当前自动程序名称 */
    TEXTRES_TEST_LANG_NAME   = 2,  /**< 测试页：当前语言名称 */
    TEXTRES_TIME_MIN         = 3,  /**< 按摩时间-分（两位数字，取自主控数据点） */
    TEXTRES_TIME_SEC         = 4,  /**< 按摩时间-秒（两位数字，取自主控数据点） */
    TEXTRES_WISE_NAME        = 5,  /**< 手动模式下当前选中的手法名（取自主控数据点） */
    TEXTRES_CURSOR_ITEM_NAME = 6,  /**< 【通用】本页【当前选中子菜单项】的名字：按 UI 游标 + 语言查 PageConfig.ItemNames */
    TEXTRES_TIME_MMSS        = 7,  /**< 【通用】按摩时间"mm:ss"（分/秒两个数据点拼成一串，组件只显示） */
    TEXTRES_ID_MAX            = 0x7FFF
} S0553_TextResId;

/**
 * @brief 图片资源ID（动态图片，与文本的 TextId 对称）
 * @details 图层填了非 0 的 ImgResId 后，实际图片序号在【发送时】按主控数据点解析，
 *          用于"同一个位置显示的图随业务状态变化"的场景（如主页程序图标）。
 */
typedef enum
{
    IMGRES_NONE = 0,
    IMGRES_MAIN_PROGRAM_ICON = 1,   /**< 主页程序图标：程序!=0→自动程序图标；程序==0(手动)→手法图标 */
    IMGRES_ITEM_STATE        = 2,   /**< 【通用】列表项选中/未选中：选中→图层 AltId，未选中→图层 Id（按图层 Index 判定） */
    IMGRES_ITEM_LARGE_ICON   = 3,   /**< 【通用】本页中间的大图标：显示当前选中子菜单项的大图（按 PageConfig.ItemLargeIcons 查表） */
    IMGRES_ITEM_ICON         = 4,   /**< 【通用】本页列表项的【小图标】：显示第 Index 项的小图标（按 PageConfig.ItemIcons 查表） */
    IMGRES_ITEM_LARGE_ICON_SELECTED = 5, /**< 【通用】中间大图选中态叠加：主控数据点（ValueDataPoint）值 == 本页游标对应业务值（cursor + ValueOffset）时，在中间大图上叠加显示该游标项的选中态大图（按 ItemLargeIconsSelected 查表）；否则整层不画（保持默认图）。状态由主控数据驱动，组件不存储。零重力/自动程序/手动手法共用 */
    IMGRES_ID_MAX             = 0x7FFF
} S0553_ImgResId;

/** @brief 图片资源解析失败返回值（此时回退图层配置的静态 Id） */
#define S0553_IMGRES_INVALID   0xFFFF

/* ================================================================================================
 * 【列表项圆底 · 弧线布局规范】所有"带子菜单可选项"的页面统一遵守
 *
 * 屏幕：240×240【圆形屏】—— 圆心 (120,120)，半径 120。
 * 圆底：24×24（IMG_COMMON_ROUND_ICON_BG / ..._SEL_BG）—— 半径 12。
 *
 * 排布：小圆【圆心】落在以【弧心 (120,110)】为圆心、半径【102】的弧上，沿下半圆弧【紧凑】排列。
 *       （弧心 = 屏幕圆心 (120,120) 上移 10px —— 因贴屏边太近，整排圆底【整体上移 10px】，
 *         使最下一项距屏幕下边缘 16px，视觉更居中。）
 *       相邻圆心【弦长固定 36px】（圆底 24，故相邻圆底【间隙 12px】），
 *       整体关于垂直中线（x=120）左右对称，最下一项落在 θ=90°（正下方）。
 *
 *       弦长 36 对应的圆心角步长：Δ = 2·asin(36 / (2×102)) ≈ 20.33°
 *           θ_i = 90° - (i - (N-1)/2)·Δ        cx = 120 + 102·cos θ ， cy = 110 + 102·sin θ
 *       最下一项外缘 y = 110+102+12 = 224 ⇒ 距屏幕【下】边缘 16px（上移前为 6px）。
 *
 * 圆心 → 图层左上角（DisplayLayer 的 X/Y 是【左上角】）： X = cx-12 ， Y = cy-12
 *
 * 已算好的【圆心】坐标（取整并保证左右对称），按项数 N 取用：
 *   N=4（菜单页）          ：(68,198)  (102,210)  (138,210)  (172,198)
 *   N=5（自动程序列表页）  ：(54,187)  (85,206)   (120,212)  (155,206)  (186,187)
 *   N=3（手动 / 坐姿列表页）：(85,206)  (120,212)  (155,206)
 *   N=6（自动程序子页）      ：(41,174)  (68,198)   (102,210)  (138,210)  (172,198)  (199,174)
 *   N=8（下机芯手法页）      ：(23,143)  (41,174)   (68,198)   (102,210)  (138,210)  (172,198)  (199,174)  (217,143)
 *   N=13（上机芯手法页，见下方【例外】）：
 *            (44,60)   (27,92)    (23,128)   (33,162)   (54,191)   (85,210)   (120,217)
 *            (155,210) (186,191)  (207,162)  (217,128)  (213,92)   (196,60)
 *
 *       对应【左上角】（= 圆心-12），直接填进图层 X/Y：
 *   N=4 ：(56,186)  (90,198)   (126,198)  (160,186)
 *   N=5 ：(42,175)  (73,194)   (108,200)  (143,194)  (174,175)
 *   N=3 ：(73,194)  (108,200)  (143,194)
 *   N=6 ：(29,162)  (56,186)   (90,198)   (126,198)  (160,186)  (187,162)
 *   N=8 ：(11,131)  (29,162)   (56,186)   (90,198)   (126,198)  (160,186)  (187,162)  (205,131)
 *   N=13：(32,48)   (15,80)    (11,116)   (21,150)   (42,179)   (73,198)   (108,205)
 *         (143,198) (174,179)  (195,150)  (205,116)  (201,80)   (184,48)
 *       （对称校验：左右两项的左上角之和 + 24 = 240）
 *
 * @note 【项数多时怎么排】仍用【同一条弧】：以最下方那项为对称中心（θ=90°），
 *       向左右两侧等角展开。项数越多，两端沿圆弧越往上绕 —— N=8 两端到 θ≈19°/161°
 *       （屏幕左右偏下），N=13 两端绕到 θ≈-38°/218°（屏幕左右偏上）。
 *
 * @note 【N=13 的例外：弧心回到屏幕中心 (120,120)、半径缩到 97】
 *       项数多到要绕到【上半部】时，不能再沿用 (120,110) + R=102：
 *       弧心上移后上半部的项会更靠外，圆底【方形图片的左上角】会捅出圆形屏幕
 *       （实测 (21,44) 距屏心 124.8 > 120，被裁掉一角）。
 *       ⇒ N=13 改用 弧心 (120,120) + R=97，此时四角最远 113.7，距屏边留 6.3px。
 *       （弦长仍 36，故圆心角步长变为 2·asin(36/194) ≈ 21.39°。）
 *
 * 图标层：小圆内居中放 14×14 图标 ⇒ 固定偏移 (+5,+5)，即 图标X = 圆底X+5 、 图标Y = 圆底Y+5。
 *
 * 标题：统一取【菜单页基准】(70,155)，24 号字（约占 y 155~179）。与弧线不冲突 ——
 *       弧线最高的一项 y=185（N=5 两端），与标题底部留 6px 间隙。
 *
 * @note 调整"贴合程度"改半径 102；调整"疏密"改弦长 36（越小越挤）。
 *       二者变化后需按上式重算各页坐标（图层是静态数组，不能用运行时三角函数）。
 *       注：圆底是 24×24 的【方形图片】（内容为圆形），其四角会比圆心更远 ——
 *       半径 ≤106 才能保证方形图片的四角也不出屏（当前 102 留有余量）。
 * ==============================================================================================*/

/**
 * @brief 按文本资源ID、主板自动程序序号、语言解析实际文本
 * @param textId       文本资源ID（S0553_TextResId）
 * @param programIndex 主板自动程序序号（0-based）
 * @param lang         当前 UI 语言（S0553_LangId）
 * @return const char* 解析到的 UTF-8 字符串（须为静态/字面量）；未匹配返回空串 ""
 */
const char* S0553UI_ResolveText(uint16_t textId, uint8_t programIndex, S0553_LangId lang);

/**
 * @brief 按图片资源ID、程序序号解析实际图片序号（与 S0553UI_ResolveText 对称）
 * @param imgResId      图片资源ID（S0553_ImgResId）
 * @param programIndex  当前程序（S0553_DP_PROGRAM：0=手动，1..N=自动程序）
 * @param lang          当前 UI 语言（当前图片与语言无关，仅为签名对称保留）
 * @param itemIndex     本层代表的列表项序号（DisplayLayer.Index）
 * @param altImageId    本层的备用图片序号（DisplayLayer.AltId，通常作"选中态"图）
 * @param defaultImageId 本层的默认图片序号（DisplayLayer.Id，通常作"未选中态"图）
 * @return uint16_t 图片序号；S0553_IMGRES_INVALID 表示【整层不画】
 * @note   itemIndex / altImageId / defaultImageId 都由【图层】携带，而非编码进 imgResId 枚举——
 *         故"新增一个列表项"只需在页面里多填一层，不必改动本枚举与解析函数。
 */
uint16_t S0553UI_ResolveImage(uint16_t imgResId, uint8_t programIndex, S0553_LangId lang,
                              uint8_t itemIndex, uint16_t altImageId, uint16_t defaultImageId);

/**
 * @brief 获取页面配置表（PageConfig 指针数组）的指针
 * @note  各页面在自己的文件里定义 const PageConfig <SYM>_Page，中心表只存其指针，
 *        故返回二级指针；遍历用 map[i]->PageType。
 */
const PageConfig *const* S0553UI_GetPageConfigTable(void);

/**
 * @brief 获取页面配置表的大小
 */
uint8_t S0553UI_GetPageConfigCount(void);

/* ==================== 全局表（供页面复用，避免复制导致不一致） ==================== */
/** @brief 手法名表（0-based，下标 = S0553_DP_WISE 值）。手动手法页 ItemNames 复用此表。 */
extern const char* s_WiseName[][S0553_LANG_MAX];

/** @brief 程序名表（0-based，下标 = 程序号 - 1）。主页与自动程序子页复用此表。 */
extern const char* s_MainProgramName[][S0553_LANG_MAX];


/***************************************************************************************************
* @file      S0553_Host.h
* @brief     页面/组件 与 主控 之间的交互框架（主控适配层）
* @details   设计原则：【主控是业务状态的唯一真相源，组件只负责"渲染 + 上报用户意图"】。
*            组件不再本地保存业务数值（已移除原 PageContext 多槽位 / PageConfig.Min-Max-Current
*            等冗余副本），只保留一张"s_DpValue 渲染镜像"：它是主控状态的【只读投影】，
*            【任何变更都必须经主控确认后回推】，组件不再自行 ++/--，从根上消除两份状态漂移。
*
*            【数据流向】只有两条通道（职责单向、互不混用）：
*            ┌──────────┬──────────────┬──────────────────────────┬──────────────────────────┐
*            │ 通道     │ 方向         │ 接口                     │ 场景                     │
*            ├──────────┼──────────────┼──────────────────────────┼──────────────────────────┤
*            │ 指令下发 │ 组件 → 主控 │ S0553_Host_SendCommand() │ 用户操作 → 主控执行      │
*            │ 状态同步 │ 主控 → 组件 │ S0553_Host_NotifyValue() │ 定时推全量 → 重绘        │
*            └──────────┴──────────────┴──────────────────────────┴──────────────────────────┘
*
*            【取数方式：纯推，组件不"拉"】
*            主控在通电期间【定时推送全部数据点】；组件收到后自行与镜像比对 ——
*            【值确实变化才触发重绘】，重复推相同值不会重绘、也不产生串口流量。
*            因此组件侧【没有】"向主控查询"的接口，主控【不需要实现任何查询回调】。
*            （早期版本有 Query 拉通道，已删除：主控定时推全量后它完全冗余。）
*
*            【"用户操作"的完整链路（第二类交互）】
*              组件短按  → S0553_Host_SendCommand() 把命令交给主控
*                       → 主控按自身运行状态【裁决】（可拒绝 / 可钳制）
*                       → 主控【只更新自己的状态】，结果【不需要】在命令回调里回推
*                       → 下一次"定时推送"把新值带回组件 → 值有变化才触发重绘
*            即：命令的【结果】走的是"状态同步"通道，最迟一个推送周期到达界面。
*            这样主控实现最简单 —— 命令回调里【不用记得回推】。
*            若某处需要"立刻生效"的手感，可在改完状态后【额外】NotifyValue 一次（可选）。
*
* 【移植边界】本文件属 Key_S0553/（移植代码）。主控侧只需做两件事：
*            ① （可选）需要接收用户操作时：定义【强符号】函数 S0553Host_OnCommand()
*               （组件初始化已自动注册其弱符号默认实现，主控定义同名函数即覆盖，
*                无需再调 S0553_Host_Register）。若产品无需在屏上改数值，不定义即可。
*            ② 通电期间【定时调用 S0553_Host_NotifyValue() 推送全部数据点】
*               （开机先推一次，避免首屏空值）。命令的执行结果【无需单独回推】——
*               它由本条定时推送带回（最迟一个推送周期）。
*            完整步骤与可填空的骨架见随包提供的
*            docs/S0553_Porting_Guide.md、docs/S0553_Porting_Template.c。
*
* @date      2026-10-22
==================================================================================================*/
#ifndef S0553_HOST_H_
#define S0553_HOST_H_

#include <stdint.h>

/* ==================== 数据点（主控持有的业务状态，组件只读投影） ==================== */
/**
 * @brief 数据点 ID
 * @details 每个需要在屏上显示、或可由旋钮调节的业务量，都建模为一个数据点。
 *          组件不持有其真值；只保存最近一次主控推送来的值用于渲染。
 * @note  新增数据点请在此枚举追加（S0553_DP_COUNT 之前）。
 */
typedef enum
{
    S0553_DP_NONE = 0,          /**< 无数据点（该页不显示/不调节数值） */
    S0553_DP_TIME_MIN,          /**< 按摩时间-分（主控下发，组件只显示；倒计时由主控维护） */
    S0553_DP_TIME_SEC,          /**< 按摩时间-秒（主控下发，组件只显示） */
    S0553_DP_PROGRAM,           /**< 当前选中的程序：0 = 手动模式；1..20 = S0553 可选自动程序 */
    S0553_DP_WISE,              /**< 【上机芯】手法序号（仅 PROGRAM==0 时有效，参考 S0553WiseId） */
    S0553_DP_WISE_LOWER,        /**< 【下机芯】手法序号（仅 PROGRAM==0 时有效；S0553 下机芯页只提供 0..6 七项） */
    S0553_DP_LANGUAGE,          /**< 当前 UI 语言（S0553_LangId），动态文本按此查表 */
    S0553_DP_POWER,             /**< 【工作状态 / 电源】由主控持有并按自身业务逻辑推送，组件据此三态显示：
                                     0     = 关机（黑屏）
                                     5     = 运行（开机正常使用：LOGO → 主页）
                                     其他  = 中间态（只显示 Logo，不进入运行页；暂停时使用）
                                     主控【不需要】调用 S0553Display_PowerOn() / PowerOff()。
                                     （早期由"旋钮长按回调"控制开关机，已废弃：工作状态属主控业务，
                                       与其余数据点一样走本条定时推送通道。） */
    S0553_DP_ZERO_GRAVITY,      /**< 零重力挡位（S0553ZeroGravityLevel）：0=关闭，1/2/3=三档，主控下发，组件按需显示 */
    S0553_DP_COUNT              /**< 数据点总数（边界，勿作为数据点使用） */
} S0553DataPoint;
/* 数据点语义（组件【只显示】，不做本地倒计时；取值范围与钳制均由主控持有）：
     时间分/秒  ← 主控维护的倒计时（主控侧的"剩余分钟 / 剩余秒"状态）
     程序       ← 主控侧的程序序号，【0 = 手动程序】，S0553 仅允许选择 1..20
     上机芯手法 ← 主控侧的【上机芯】手法序号（S0553WiseId），仅在"程序==0(手动)"时有效
     下机芯手法 ← 主控侧的【下机芯】手法序号，仅在"程序==0(手动)"时有效；
                  S0553 下机芯页只提供 0..6 七项
     语言       ← 主控侧的语言选择
     工作状态   ← 主控侧的工作状态经主控自身映射后的显示结果：0=关机黑屏，5=运行，
                  其他=中间态（组件只显示 Logo）；映射权在主控
     零重力     ← 主控侧的零重力挡位（0=关闭，1/2/3=三档）
   即"当前选中的程序"由【程序 + 上/下机芯手法】三个数据点共同表达：
     - 程序 != 0 → 自动程序，显示对应程序名；
     - 程序 == 0 → 手动程序，具体手法按【上机芯手法 / 下机芯手法】两个数据点区分。 */

/* ==================== 手法 ID（S0553_DP_WISE 的取值域） ==================== */
/**
 * @brief 手动模式下的手法 ID
 * @details S0553_DP_WISE 只在本枚举内取值：0 = 无手法，1..11 = 11 种手法。
 *          与 Layer/S0553_UI_Config.c 的 s_WiseName 表【逐行对齐】（下标 = 枚举值）。
 *          组件短按手法项时，通过【每页的"游标 → 手法"映射表】把 UI 游标转换为
 *          对应枚举值再下发给主控 —— 主控侧 switch/case 即可用语义名而非裸数字。
 *          增删手法：① 同步改本枚举；② 同步改 s_WiseName 表；③ 改各页映射表。
 */
typedef enum
{
    S0553_WISE_NONE          = 0,  /**< 无手法（手动模式未选具体手法） */
    S0553_WISE_KNEAD         = 1,  /**< 揉捏 */
    S0553_WISE_TAP_1         = 2,  /**< 拍打1 */
    S0553_WISE_TAP_2         = 3,  /**< 拍打2 */
    S0553_WISE_KNEAD_TAP     = 4,  /**< 揉捏拍打 */
    S0553_WISE_SHIATSU_1     = 5,  /**< 指压1 */
    S0553_WISE_SHIATSU_2     = 6,  /**< 指压2 */
    S0553_WISE_SHOULDER_GRAB = 7,  /**< 肩部提抓 */
    S0553_WISE_4D_1          = 8,  /**< 4D I */
    S0553_WISE_4D_2          = 9,  /**< 4D II */
    S0553_WISE_4D_3          = 10, /**< 4D III */
    S0553_WISE_4D_4          = 11, /**< 4D IV */
    S0553_WISE_COUNT              /**< 手法 ID 总数（含"无手法"，作边界勿用） */
} S0553WiseId;

/* ==================== 零重力挡位（S0553_DP_ZERO_GRAVITY 的取值域） ==================== */
/**
 * @brief 零重力挡位
 * @details S0553_DP_ZERO_GRAVITY 只在本枚举内取值：0 = 关闭，1/2/3 = 三档。
 *          与 Layer/S0553_Page_PostureItem2.c 的零重力项对应：1/2/3 档对应其零重力1/2/3项。
 */
typedef enum
{
    S0553_ZERO_G_OFF = 0,  /**< 关闭零重力 */
    S0553_ZERO_G_1,        /**< 零重力 1 档 */
    S0553_ZERO_G_2,        /**< 零重力 2 档 */
    S0553_ZERO_G_3,        /**< 零重力 3 档 */
    S0553_ZERO_G_COUNT     /**< 档位数（含关闭态，共 4），作边界勿用 */
} S0553ZeroGravityLevel;

/**
 * @brief 坐姿动作（S0553_HCMD_POSTURE / S0553_HCMD_POSTURE_STOP 命令的 arg 取值，【非数据点】）
 * @details 4 个部件（联动 / 靠背 / 小腿 / 足部）× 2 个方向（升 / 降）= 8 种。
 *          坐姿电机是【持续运行型】：收到"开始"命令即朝该方向持续运行，直到收到
 *          "停止"命令、或到达限位自动停（电机有限位，无需额外过流/堵转保护）。
 *          因此坐姿命令【拆成两条】，而非"点按一次执行一次"：
 *            · S0553_HCMD_POSTURE      = 开始该动作（arg = 本枚举值，持续运行）
 *            · S0553_HCMD_POSTURE_STOP = 停止当前坐姿动作（arg = 0）
 *          不建模为数据点（无需回推状态、界面不显示坐姿当前值）。
 *          组件在"旋转"时【每格】发一次 S0553_HCMD_POSTURE（开始，方向即本枚举值），
 *          在"短按退出调节态 / 返回主页 / 进入页面"或检测到停手时，
 *          组件发 S0553_HCMD_POSTURE_STOP（明确停止）；主控无需额外实现停手看护。
 */
typedef enum
{
    S0553_POSTURE_LINKAGE_UP   = 0,  /**< 联动-升 */
    S0553_POSTURE_LINKAGE_DOWN,      /**< 联动-降 */
    S0553_POSTURE_BACKREST_UP,       /**< 靠背-升 */
    S0553_POSTURE_BACKREST_DOWN,     /**< 靠背-降 */
    S0553_POSTURE_CALF_UP,           /**< 小腿-升 */
    S0553_POSTURE_CALF_DOWN,         /**< 小腿-降 */
    S0553_POSTURE_FOOT_UP,           /**< 足部-升 */
    S0553_POSTURE_FOOT_DOWN,         /**< 足部-降 */
    S0553_POSTURE_COUNT              /**< 坐姿动作总数（8），作边界勿用 */
} S0553PostureId;

/* ==================== 组件 → 主控 指令 ==================== */
/**
 * @brief 组件下发给主控的操作意图
 * @details 组件只表达"用户想做什么"，不自行改值；由主控裁决（含范围钳制）后回推状态。
 */
typedef enum
{
    S0553_HCMD_NONE = 0,
    S0553_HCMD_ADJUST,          /**< 相对调整：arg = +1 / -1（新值由主控裁决） */
    S0553_HCMD_SET,             /**< 直接设置：arg = 目标值（数据点命令） */
    S0553_HCMD_POSTURE,         /**< 坐姿动作-开始（非数据点）：dp 传 S0553_DP_NONE，arg = S0553PostureId（持续运行，直到 STOP/限位/看护超时） */
    S0553_HCMD_POSTURE_STOP     /**< 坐姿动作-停止（非数据点）：dp 传 S0553_DP_NONE，arg = 0（停止当前坐姿动作） */
} S0553HostCommand;

/* ==================== 主控侧需实现的回调 ==================== */
/**
 * @brief 指令下发回调（组件 → 主控 推）
 * @param cmd 指令类型（ADJUST / SET / POSTURE / POSTURE_STOP）
 * @param dp  数据点命令时 = 作用的数据点；坐姿动作命令时传 S0553_DP_NONE
 * @param arg 指令参数（ADJUST 为 ±1；SET 为目标值；POSTURE 为坐姿动作 S0553PostureId；POSTURE_STOP 为 0）
 * @note  主控【只需按裁决结果更新自己的状态】，【不需要】在本回调里回推 ——
 *        结果由"定时推送全部数据点"带回组件（最迟一个推送周期）。
 *        若某处需要"立刻生效"的手感，可在此【额外】调一次 S0553_Host_NotifyValue()（可选）。
 */
typedef void (*S0553HostCommandCb)(S0553HostCommand cmd, S0553DataPoint dp, int16_t arg);

/**
 * @brief 数据变更回调（主控推送的值【确实发生变化】时触发，由显示组件注册）
 * @param dp        变化的数据点
 * @param oldValue  变化前值
 * @param newValue  变化后值
 * @note  组件【自行判断是否刷新】：本回调只在"值确实变了"或"首次收到"时触发，
 *        主控重复推送相同值不会产生任何重绘 —— 这正是纯推模式不会刷屏的原因。
 */
typedef void (*S0553HostValueChangedCb)(S0553DataPoint dp, uint8_t oldValue, uint8_t newValue);

/**
 * @brief 主控能力接口集合（由主控在启动时注册）
 * @note  只有 Command 一项：取数走【主控定时推送】，组件不查询。
 */
typedef struct
{
    S0553HostCommandCb Command;   /**< 指令下发（可为 NULL：用户调节不生效） */
} S0553HostOps;

/* ---- 弱符号宏：主控可覆盖的默认回调（量产 MCU 编译器语法不同，统一封装） ---- */
#if defined(__GNUC__)
    #define S0553_WEAK  __attribute__((weak))
#elif defined(__IAR_SYSTEMS_ICC__) || defined(__CC_ARM) || defined(__ARMCC_VERSION)
    #define S0553_WEAK  __weak
#else
    #define S0553_WEAK  /* 未知编译器：退化为普通函数，主控需显式 Register */
#endif

/**
 * @brief 主控接收用户操作命令的【默认弱符号】回调
 * @note  组件在 S0553_Host_Init() 里自动把本函数注册为主控接口，主控【无需】再调 Register。
 *        主控要接收命令，只需在任意 .c 里定义【同名强符号】函数覆盖本弱符号即可：
 *            void S0553Host_OnCommand(S0553HostCommand cmd, S0553DataPoint dp, int16_t arg);
 *        不定义则落到弱符号空实现 —— 屏上调节不生效，但显示照常。
 */
void S0553Host_OnCommand(S0553HostCommand cmd, S0553DataPoint dp, int16_t arg);

/* ==================== 框架接口 ==================== */

/**
 * @brief 组件内部初始化：自动注册默认主控接口（指向弱符号 S0553Host_OnCommand）
 * @note  由 S0553_Init() 内部调用，主控【不需要】调用本函数。
 */
void S0553_Host_Init(void);

/**
 * @brief 主控注册其能力接口（可选；传 NULL 注销）
 * @param ops 主控实现；注册后镜像标记失效，等待主控下一次定时推送填充
 * @note  【通常不需要调用】—— 组件已自动注册弱符号默认接口；
 *        仅当主控要【运行时切换】实现时才调用。传 NULL 注销（回落到不处理）。
 */
void S0553_Host_Register(const S0553HostOps *ops);

/**
 * @brief 取数据点当前值（【只读】渲染镜像；不发起任何查询）
 * @param dp 数据点
 * @return 当前值；主控【尚未推送过】时为 0
 * @note  取值【不会】触发向主控请求 —— 数据一律由主控定时推送（纯推模式）。
 */
uint8_t S0553_Host_GetValue(S0553DataPoint dp);

/**
 * @brief 【主控 → 组件】状态同步：主控推送数据点当前值（唯一的入方向通道）
 * @param dp    数据点
 * @param value 当前值
 * @note  组件内部与镜像比对：【值没变就不做任何事】（不重绘、不发帧）；
 *        值变了（或首次收到）才触发已注册的 ValueChanged 回调 → 刷新界面。
 *        因此【可以放心地定时推送全部数据点】，不会因重复推相同值而刷屏。
 */
void S0553_Host_NotifyValue(S0553DataPoint dp, uint8_t value);

/**
 * @brief 注册数据变更回调（由显示组件在初始化时注册；主控侧无需关心）
 * @param cb 回调（可为 NULL 注销）
 */
void S0553_Host_SetValueChangedCb(S0553HostValueChangedCb cb);

/**
 * @brief 【组件 → 主控】下发操作指令（不本地改值，发完即返回）
 */
void S0553_Host_SendCommand(S0553HostCommand cmd, S0553DataPoint dp, int16_t arg);

#endif /* S0553_HOST_H_ */
